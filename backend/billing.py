"""Authenticated checkout/portal and verified durable webhook intake.

This Lambda never has write access to the Pro entitlement table. Only the private
billing worker can materialize access after fetching authoritative Dodo records.
"""

import json
import logging
import os
import time
import uuid

from standardwebhooks.webhooks import Webhook, WebhookVerificationError

try:
    from . import dodo
    from .accounts import table, require_session
    from .auth import AccessError, authenticate
    from .controls import conditional_failure, fields, transaction
    from .handler import response, event_body, event_method, event_path
except ImportError:
    import dodo
    from accounts import table, require_session
    from auth import AccessError, authenticate
    from controls import conditional_failure, fields, transaction
    from handler import response, event_body, event_method, event_path


logger = logging.getLogger("focusfeed.billing")
MAX_BODY = 128_000


def store():
    return table(os.environ["FOCUSFEED_BILLING_TABLE"])


def key(kind, value, sk="STATE"):
    return {"pk": "DODO#" + dodo.config(require_key=False)["mode"] + "#" + kind + "#" + value, "sk": sk}


def read(kind, value, sk="STATE"):
    return store().get_item(Key=key(kind, value, sk), ConsistentRead=True).get("Item", {})


def return_url():
    from urllib.parse import urlsplit
    value = os.getenv("DODO_RETURN_URL", "")
    parsed = urlsplit(value)
    if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment:
        raise AccessError(503, "billing_unavailable", "The billing return page has not been configured.")
    return value


def status(principal):
    settings = dodo.config()
    user = read("USER", principal.subject)
    return {"available": True, "mode": settings["mode"], "canManage": bool(user.get("customerId")),
            "hasSubscription": bool(user.get("hasSubscription")), "cancelAtPeriodEnd": bool(user.get("cancelAtPeriodEnd")),
            "accessUntil": int(user.get("accessUntil", 0)), "subscriptionStatus": user.get("subscriptionStatus", "none")}


def enqueue(kind, resource, subject=None):
    # Client refresh IDs are generated by the server and scoped to the caller.
    event_id = uuid.uuid4().hex
    item = {**key("EVENT", event_id, "EVENT"), "kind": kind, "resource": resource,
            "eventId": event_id, "status": "pending", "createdAt": int(time.time()),
            "expiresAt": int(time.time()) + 30 * 86400}
    if subject:
        item["subject"] = subject
    store().put_item(Item=item, ConditionExpression="attribute_not_exists(pk)")


def throttle(subject, action, interval=60):
    now = int(time.time())
    try:
        store().update_item(Key=key("RATE", subject + "#" + action),
            UpdateExpression="SET allowedAfter = :after, expiresAt = :ttl",
            ConditionExpression="attribute_not_exists(allowedAfter) OR allowedAfter <= :now",
            ExpressionAttributeValues={":after": now + interval, ":now": now, ":ttl": now + 86400})
    except Exception as exc:
        if conditional_failure(exc):
            raise AccessError(429, "billing_rate_limit", "Please wait a moment before trying again.") from exc
        raise


def checkout(principal):
    settings = dodo.config()
    user, now = read("USER", principal.subject), int(time.time())
    if user.get("hasSubscription"):
        raise AccessError(409, "subscription_exists", "Manage your existing subscription instead of purchasing again.")
    if user.get("checkoutUntil", 0) > now and user.get("checkoutId"):
        session = dodo.request("GET", "/checkouts/" + dodo.identifier(user["checkoutId"]))
        if session.get("payment_status") not in ("failed", "cancelled"):
            if session.get("payment_status") == "succeeded":
                enqueue("payment", dodo.identifier(session["payment_id"]))
                raise AccessError(409, "payment_pending", "Your payment is being confirmed. Refresh access shortly.")
            return {"url": dodo.link(user["checkoutUrl"], "checkout"), "mode": settings["mode"]}
    throttle(principal.subject, "checkout")
    intent = uuid.uuid4().hex
    # Commit the trusted account/intent association BEFORE requesting checkout.
    # Even a provider response lost before persistence can never grant another user.
    transaction([
        {"Put": {"TableName": os.environ["FOCUSFEED_BILLING_TABLE"], "Item": fields({
            **key("INTENT", intent), "subject": principal.subject, "productId": settings["product"],
            "createdAt": now, "expiresAt": now + 7 * 86400}), "ConditionExpression": "attribute_not_exists(pk)"}},
        {"Update": {"TableName": os.environ["FOCUSFEED_BILLING_TABLE"], "Key": fields(key("USER", principal.subject)),
            "UpdateExpression": "SET checkoutIntent = :intent, checkoutLockUntil = :until, reconcileGroup = :group, reconcileAt = :due",
            "ConditionExpression": "attribute_not_exists(checkoutLockUntil) OR checkoutLockUntil < :now",
            "ExpressionAttributeValues": fields({":intent": intent, ":until": now + 30, ":now": now,
                                                 ":group": settings["mode"], ":due": now + 900})}},
    ])
    body = {"product_cart": [{"product_id": settings["product"], "quantity": 1}],
            "metadata": {"focusfeed_intent": intent}, "return_url": return_url(),
            "subscription_data": {"trial_period_days": 0}}
    if user.get("customerId"):
        body["customer"] = {"customer_id": dodo.identifier(user["customerId"])}
    session = dodo.request("POST", "/checkouts", body)
    session_id = dodo.identifier(session.get("session_id"))
    url = dodo.link(session.get("checkout_url"), "checkout")
    transaction([
        {"Put": {"TableName": os.environ["FOCUSFEED_BILLING_TABLE"], "Item": fields({
            **key("CHECKOUT", session_id), "intent": intent, "subject": principal.subject,
            "productId": settings["product"], "expiresAt": now + 7 * 86400}), "ConditionExpression": "attribute_not_exists(pk)"}},
        {"Update": {"TableName": os.environ["FOCUSFEED_BILLING_TABLE"], "Key": fields(key("USER", principal.subject)),
            "UpdateExpression": "SET checkoutId = :id, checkoutUrl = :url, checkoutUntil = :until REMOVE checkoutLockUntil",
            "ConditionExpression": "checkoutIntent = :intent",
            "ExpressionAttributeValues": fields({":intent": intent, ":id": session_id, ":url": url, ":until": now + 86400})}},
    ])
    return {"url": url, "mode": settings["mode"]}


def portal(principal):
    user = read("USER", principal.subject)
    customer = user.get("customerId")
    if not customer or read("CUSTOMER", customer).get("subject") != principal.subject:
        raise AccessError(404, "billing_customer_missing", "No billing account is linked yet. Wait for payment confirmation.")
    throttle(principal.subject, "portal", 10)
    session = dodo.request("POST", "/customers/" + dodo.identifier(customer) + "/customer-portal/session",
                           query={"return_url": return_url(), "send_email": "false"})
    return {"url": dodo.link(session.get("link"), "portal"), "mode": dodo.config()["mode"]}


def webhook(event):
    secret = os.getenv("DODO_WEBHOOK_SECRET", "")
    if not secret:
        raise AccessError(503, "billing_unavailable", "Webhook verification has not been configured.")
    raw = event_body(event)
    if len(raw) > MAX_BODY:
        raise AccessError(413, "body_too_large", "Webhook body is too large.")
    headers = {str(k).lower(): v for k, v in (event.get("headers") or {}).items()}
    try:
        payload = Webhook(secret).verify(raw, headers)
    except (WebhookVerificationError, ValueError, TypeError, KeyError) as exc:
        raise AccessError(401, "invalid_webhook", "Invalid webhook signature.") from exc
    if not isinstance(payload, dict) or payload.get("business_id") != dodo.config(require_key=False)["business"]:
        raise AccessError(401, "invalid_webhook", "Invalid webhook business.")
    event_type, data = payload.get("type", ""), payload.get("data", {})
    if not isinstance(event_type, str) or not isinstance(data, dict):
        raise AccessError(400, "invalid_webhook", "Invalid webhook payload.")
    kind = event_type.split(".")[0]
    if kind not in ("subscription", "payment", "refund", "dispute"):
        return {"received": True}
    # Refund/dispute payloads carry the parent payment ID. Re-fetch its current
    # state so refunds arriving before a payment webhook cannot resurrect access.
    resource = dodo.identifier(data.get("subscription_id") if kind == "subscription" else data.get("payment_id"))
    event_id = dodo.identifier(headers.get("webhook-id"))
    try:
        store().put_item(Item={**key("EVENT", event_id, "EVENT"), "kind": kind, "resource": resource,
            "eventId": event_id, "status": "pending", "createdAt": int(time.time()),
            "expiresAt": int(time.time()) + 30 * 86400}, ConditionExpression="attribute_not_exists(pk)")
    except Exception as exc:
        if not conditional_failure(exc):
            raise
    return {"received": True}


def lambda_handler(event, _context):
    method, path = event_method(event), event_path(event)
    try:
        if method == "GET" and path == "/billing/return":
            # Query parameters are deliberately ignored; they never authorize Pro.
            return {"statusCode": 200, "headers": {"content-type": "text/html; charset=utf-8", "cache-control": "no-store",
                "content-security-policy": "default-src 'none'; frame-ancestors 'none'", "referrer-policy": "no-referrer"},
                "body": "<!doctype html><html lang=en><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'><title>OwnFeed billing</title><h1>Return to OwnFeed</h1><p>Your payment status is confirmed securely in the background. Open the extension and choose Refresh access. Confirmation can take a few minutes.</p></html>"}
        if method == "POST" and path == "/billing/webhook":
            return response(200, webhook(event))
        if (method, path) not in {("GET", "/billing/status"), ("POST", "/billing/checkout"), ("POST", "/billing/portal"), ("POST", "/billing/refresh")}:
            return response(404, {"error": {"code": "not_found", "message": "Route not found."}})
        principal = authenticate(event)
        if principal.local:
            raise AccessError(403, "billing_requires_account", "Sign in to a hosted account before using billing.")
        require_session(principal)
        if method == "POST":
            raw = event_body(event)
            if len(raw) > 1000 or raw and json.loads(raw) != {}:
                raise AccessError(400, "invalid_billing_request", "Billing requests cannot override account, price or product details.")
        if path == "/billing/status":
            return response(200, status(principal))
        if path == "/billing/checkout":
            return response(200, checkout(principal))
        if path == "/billing/portal":
            return response(200, portal(principal))
        throttle(principal.subject, "refresh", 30)
        enqueue("account", principal.subject, principal.subject)
        return response(202, {"refreshing": True})
    except AccessError as exc:
        return response(exc.status, {"error": {"code": exc.code, "message": str(exc)}})
    except (ValueError, TypeError, UnicodeError):
        return response(400, {"error": {"code": "invalid_billing_request", "message": "Invalid billing request."}})
    except Exception:
        logger.warning('{"event":"billing_storage_failure"}')
        return response(503, {"error": {"code": "billing_unavailable", "message": "Billing is temporarily unavailable. Try again shortly."}})

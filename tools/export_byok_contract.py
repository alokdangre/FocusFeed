"""Export the existing Python classifier's exact question templates for the worker.

Run with backend/.venv/bin/python tools/export_byok_contract.py [--check].
No provider requests. Keep the backend and BYOK filtering semantics aligned.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend import classifier, channel_classifier
from backend.models import ClassificationRequest, ObjectiveClassificationRequest
from backend.taxonomy import TOPICS_BY_ID, TAXONOMY_VERSION


def content():
    intent = {"id": "intent-example", "text": "movie reviews", "contentType": "topic",
              "matchScope": "intent", "validationVersion": "focusfeed-intent-v1"}
    topic = next(iter(TOPICS_BY_ID.values()))
    taxonomy = {"id": topic.id, "text": topic.label, "contentType": "topic", "matchScope": "taxonomy",
                "taxonomyId": topic.id, "taxonomyVersion": TAXONOMY_VERSION}
    profile = {"id": "general", "version": 1, "mode": "general", "objectives": [intent]}

    def video_question(objective, mode="general", collection=False):
        video = {"videoId": "examplevideo", "title": "Example"}
        if collection:
            video.update(videoId="collection:RDexample", itemType="collection", collectionId="RDexample")
        request = ClassificationRequest.model_validate({"requestId": "contract-example", "profile": {
            **profile, "mode": mode, "objectives": [objective]}, "videos": [video]})
        return classifier.build_typesafe_request(request)["questions"]["v0_o0_match"]

    def channel_question(summary=False):
        channel = {"channelId": "UCexample12345", "knownTopics": ["Movie reviews"] if summary else []}
        request = channel_classifier.ChannelClassificationRequest.model_validate({
            "requestId": "contract-example", "profile": profile, "channel": channel})
        return channel_classifier.build_channel_request(request)["questions"]["o0_dominant"]

    objective = ObjectiveClassificationRequest(requestId="contract-example", mode="general", objectives=["movie reviews"])
    payload = {"model": classifier.DEFAULT_MODEL_ID, "videoVersion": classifier.VIDEO_PROMPT_VERSION,
               "objectiveVersion": classifier.OBJECTIVE_PROMPT_VERSION,
               "channelVersion": channel_classifier.CHANNEL_PROMPT_VERSION,
               "taxonomyVersion": TAXONOMY_VERSION,
               "questions": {"objective": classifier.build_objective_typesafe_request(objective)["questions"]["o0_nonsense"],
                             "intent": video_question(intent), "taxonomy": video_question(taxonomy),
                             "collectionGeneral": video_question(intent, collection=True),
                             "collectionFocus": video_question(intent, "focus", True),
                             "channelUploads": channel_question(), "channelSummary": channel_question(True)},
               "taxonomy": {key: {"taxonomy_id": value.id, "label": value.label, "definition": value.definition,
                                  "includes": list(value.includes), "excludes": list(value.excludes)}
                            for key, value in TOPICS_BY_ID.items()}}
    return "// Generated by tools/export_byok_contract.py; edit the canonical backend prompts.\n" + \
        "globalThis.FocusFeedByokContract = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "extension" / "byok-contract.js"
    expected = content()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            parser.exit(1, "BYOK contract is stale; regenerate it with this script.\n")
        print("BYOK prompts match the canonical backend.")
    else:
        target.write_text(expected)
